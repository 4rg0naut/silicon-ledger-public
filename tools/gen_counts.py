#!/usr/bin/env python3
"""gen_counts.py — derive results/COUNTS.json, the single source of every count a front door quotes.

Everything is computed from tracked data, never typed: measurements.json, the three openclaims event
files, results/EXP-* directories, results/MACHINES.md (Tested table) and tools/instruments.jsonl.
Deterministic: same inputs give byte-identical output.

experiments = distinct EXP numbers that have a README (EXP-023 is a twin slot: two dirs, one number;
an in-flight experiment with no README yet is listed under `in_flight`, not counted).

usage: python3 tools/gen_counts.py [--write | --print]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "COUNTS.json"
WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight"]


def jsonl_count(path: Path, event_type: str) -> int:
    n = 0
    for raw in path.read_text(errors="replace").splitlines():
        if raw.strip() and json.loads(raw).get("event_type") == event_type:
            n += 1
    return n


def machines() -> list[dict]:
    text = (ROOT / "results" / "MACHINES.md").read_text(errors="replace")
    sec = text.split("## Tested", 1)[1].split("\n## ", 1)[0]
    out = []
    for line in sec.splitlines():
        if not line.startswith("|") or line.startswith("|---") or line.startswith("| platform"):
            continue
        c = [x.strip().replace("**", "") for x in line.strip().strip("|").split("|")]
        if len(c) < 7:
            continue
        chip, machine, os_ = c[1], c[3], c[6]
        form = next((f for f in ("mini", "Studio", "Air") if f in machine), "")
        short = re.sub(r"\s*\(.*?\)|\s+base\b", "", chip).strip()
        out.append({"label": f"{short} {form}".strip(), "chip": chip, "machine": machine, "os": os_})
    return out


def build() -> dict:
    rows = json.loads((ROOT / "results" / "measurements.json").read_text())["measurements"]
    ocl = ROOT / "knowledge" / "ane" / "openclaims"
    e = jsonl_count(ocl / "claims-emitted.jsonl", "claim.emitted")
    v = jsonl_count(ocl / "claims-verified.jsonl", "claim.verified")
    d = jsonl_count(ocl / "claims-disputed.jsonl", "claim.disputed")
    dirs = sorted(p.name for p in (ROOT / "results").glob("EXP-*") if p.is_dir())
    with_readme = [x for x in dirs if (ROOT / "results" / x / "README.md").exists()]
    nums = lambda xs: sorted({int(re.match(r"EXP-(\d+)-", x).group(1)) for x in xs})
    allnums = nums(dirs)
    inst = [json.loads(l) for l in (ROOT / "tools" / "instruments.jsonl").read_text().splitlines() if l.strip()]
    ms = machines()
    labels = [m["label"] for m in ms]
    listing = ", ".join(labels[:-1]) + (f" and {labels[-1]}" if len(labels) > 1 else "".join(labels))
    return {
        "_note": "generated by tools/gen_counts.py from tracked data (run tools/gen_all.sh --write); never hand-edit",
        "measurements": len(rows),
        "claims_emitted": e,
        "claims_verified": v,
        "claims_disputed": d,
        "spine_events": e + v + d,
        "experiments": len(nums(with_readme)),
        "experiment_dirs": len(dirs),
        "experiment_range": f"EXP-{allnums[0]:03d}..{allnums[-1]:03d}",
        "in_flight": [x for x in dirs if x not in with_readme],
        "machines": ms,
        "machines_phrase": f"{WORDS[len(ms)]} Macs ({listing})",
        "machines_list": ", ".join(labels),
        "hardware_id": dict(sorted(Counter(r.get("hardware_id", "unset") for r in rows).items())),
        "project": dict(sorted(Counter(r.get("project", "unset") for r in rows).items())),
        "registered_instruments": len(inst),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if a.write:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
