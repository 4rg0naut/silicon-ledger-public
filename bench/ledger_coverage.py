#!/usr/bin/env python3
"""ledger_coverage.py — which hardware-lane experiments (EXP-024..047) have rows in the ledger.

Read-only. For each results/EXP-NNN-* directory with NNN in 024..047 it reports:
  * ledger rows attributed to it (audit report, `expNNN-` id prefix, or EXP dir name in `command`)
  * data files that hold numbers but are NOT ledger rows (.tsv/.jsonl/.json/.txt under results/ and raw/,
    plus the README) with sizes
  * status: covered (rows exist and the experiment has no un-ledgered result tables),
            partial (rows exist but result tables exist beyond them),
            none (no rows)
It imports nothing. The way in is `bench/build_measurements.py` + `bench/verify_extraction.py` (RULES 3).

usage: python3 bench/ledger_coverage.py [--out docs/reshape/LEDGER-COVERAGE.md]
"""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
DATA_EXT = {".tsv", ".jsonl", ".ndjson", ".json", ".txt", ".csv"}


def exp_no(name):
    m = re.match(r"EXP-(\d{3})-", name)
    return int(m.group(1)) if m else None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/reshape/LEDGER-COVERAGE.md")
    a = ap.parse_args()
    rows = json.loads((RES / "measurements.json").read_text())["measurements"]
    aud = {r["id"]: r.get("report") for r in json.loads((RES / "audit_measurements.json").read_text())["rows"]}
    dirs = sorted(p.name for p in RES.glob("EXP-*") if p.is_dir() and 24 <= (exp_no(p.name) or 0) <= 47)

    rows_by = defaultdict(set)
    for r in rows:
        rid = r["id"]
        rep = aud.get(rid)
        if rep in dirs:
            rows_by[rep].add(rid)
        m = re.match(r"exp(\d{3})-", rid)
        if m:
            for d in dirs:
                if d.startswith(f"EXP-{m.group(1)}-"):
                    rows_by[d].add(rid)
        cmd = str(r.get("command") or "")
        for d in dirs:
            if d in cmd:
                rows_by[d].add(rid)

    L = ["# Ledger coverage — hardware-lane experiments EXP-024..047", "",
         "Generated by `bench/ledger_coverage.py` (read-only). Nothing was imported. A row counts for an experiment when the "
         "audit attributes it to that README, its id starts with `expNNN-`, or its `command` names the directory. "
         "Un-ledgered numbers sit in result tables outside `measurements.json`; the sanctioned way in is "
         "`bench/build_measurements.py` + `bench/verify_extraction.py` (RULES 3), after the owner decides which "
         "tables deserve rows.", "",
         "| experiment | ledger rows | status | un-ledgered data files (count, KiB) | largest |", "|---|---|---|---|---|"]
    detail = []
    summary = {"covered": 0, "partial": 0, "none": 0}
    for d in dirs:
        alldata = [p for p in (RES / d).rglob("*") if p.is_file() and p.suffix.lower() in DATA_EXT]
        files = [p for p in alldata if "raw" not in p.relative_to(RES / d).parts]
        raw = [p for p in alldata if "raw" in p.relative_to(RES / d).parts]
        n = len(rows_by[d])
        tables = [p for p in files if p.name != "README.md"]
        if d.endswith("nax-quiet-retake"):
            status = "in-flight"
        elif d.startswith("EXP-029") and n == 0:
            status = "none"
        elif n and not tables:
            status = "covered"
        elif n:
            status = "partial"
        else:
            status = "none" if (tables or raw or (RES / d / "README.md").exists()) else "none"
        if status in summary:
            summary[status] += 1
        kib = sum(p.stat().st_size for p in tables) / 1024
        big = max(tables, key=lambda p: p.stat().st_size, default=None)
        L.append(f"| `{d}` | {n} | {status} | {len(tables)} result file(s), {kib:.0f} KiB (+{len(raw)} raw) | "
                 f"{('`'+str(big.relative_to(ROOT))+'`') if big else '-'} |")
        if status in ("partial", "none") and tables:
            detail.append((d, status, sorted(tables, key=lambda p: -p.stat().st_size)[:6]))
    L += ["", "EXP-029's result count includes files a still-running quiet-window campaign keeps writing "
          "(`results/quiet-*-campaign-*.txt`); its figure will change until the campaign ends.", "",
          f"Totals: {summary['covered']} covered, {summary['partial']} partial, {summary['none']} none "
          f"(+ in-flight exceptions) across {len(dirs)} experiments.", "",
          "`in-flight` = EXP-038 (certified-quiet window still running; not a gap).", "",
          "## Where the un-ledgered numbers are", ""]
    for d, status, fs in detail:
        L.append(f"### {d} ({status})")
        for p in fs:
            L.append(f"- `{p.relative_to(ROOT)}` ({p.stat().st_size/1024:.0f} KiB)")
        L.append("")
    out = Path(a.out)
    out = out if out.is_absolute() else ROOT / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out.relative_to(ROOT)} — {summary}, {len(dirs)} experiments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
